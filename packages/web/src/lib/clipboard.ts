// Browser clipboard helper shared by the copy controls (the AI agents page, §25.9; the
// new-challenge page's public form link, §6.1).

/** Copies `text`; falls back to a hidden textarea where the async clipboard is unavailable
 *  (a non-secure context). Resolves false when neither works. */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    /* fall through to the legacy path */
  }
  try {
    const area = document.createElement("textarea");
    area.value = text;
    area.setAttribute("readonly", "");
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(area);
    return ok;
  } catch {
    return false;
  }
}
